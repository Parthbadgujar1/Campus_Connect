export const allPeople: Person[] = [me, ...students, ...faculty, ...admins, ...businessPeople];

const byId = new Map(allPeople.map((person) => [person.id, person]));

export function getPerson(id: string): Person {
  return byId.get(id) ?? { ...students[0]!, id, name: 'Campus member', username: 'member' };
}

export function getPersonByUsername(username: string): Person | undefined {
  if (username === 'me' || username === me.username) return me;
  return allPeople.find((person) => person.username === username);
}

